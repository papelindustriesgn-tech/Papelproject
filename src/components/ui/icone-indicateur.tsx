import {
  AlertTriangle,
  BarChart3,
  Boxes,
  CalendarCheck,
  CalendarClock,
  Clock,
  Coins,
  Factory,
  Gauge,
  HandCoins,
  Landmark,
  type LucideIcon,
  MapPin,
  Package,
  Percent,
  Receipt,
  Route,
  Scale,
  ShieldCheck,
  ShoppingCart,
  Ship,
  Store,
  Timer,
  TrendingUp,
  Truck,
  Users,
  Wallet,
  Wrench,
} from "lucide-react";

/** Icône d'un indicateur, déduite de son libellé (les 100+ tuiles de l'ERP en ont une sans configuration). */
const REGLES: [RegExp, LucideIcon][] = [
  [/temps moyen/i, Timer],
  [/marge|résultat|bénéfice|rentabilit/i, Coins],
  [/chiffre d'affaires|ventes|revenu/i, TrendingUp],
  [/trésorerie|caisse|banque|argent disponible/i, Landmark],
  [/créance|impay|dso|délai moyen de paiement|nous doivent|reste à payer|dû par/i, HandCoins],
  [/encaissement|net à payer|paie|salari|coût salarial/i, Wallet],
  [/dette|fournisseur|bfr|argent bloqué/i, Scale],
  [/prix|coût|dépense/i, Receipt],
  [/commande/i, ShoppingCart],
  [/client|effectif|employ|présent|commerciaux|grossiste/i, Users],
  [/point(s)? de vente|pva/i, Store],
  [/visite|couverture/i, MapPin],
  [/rupture|alerte|non-conformit|problème|panne|critique|absent/i, AlertTriangle],
  [/livrées à temps/i, Truck],
  [/rendement|trs|efficacité|disponibilit|taux|part|conformit|réussi/i, Gauge],
  [/perte|retour|écart/i, Percent],
  [/arrêt|mttr|mtbf|temps/i, Timer],
  [/papier|production|fabrication/i, Factory],
  [/transit|conteneur/i, Ship],
  [/colis|stock|matière|produits finis|bobine|volumes/i, Boxes],
  [/livraison|tournée|bons|kilom/i, Truck],
  [/contrat|congé|demande/i, CalendarClock],
  [/absentéisme|présence/i, CalendarCheck],
  [/préventif|maintenance|pièce/i, Wrench],
  [/qualité|contrôle/i, ShieldCheck],
  [/délai|jours/i, Clock],
  [/route|km/i, Route],
  [/valeur/i, Package],
];

export function IconeIndicateur({ libelle, size = 20 }: { libelle: string; size?: number }) {
  const Icone = REGLES.find(([r]) => r.test(libelle))?.[1] ?? BarChart3;
  return <Icone size={size} aria-hidden />;
}
